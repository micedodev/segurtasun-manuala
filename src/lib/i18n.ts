export function otherLang(l: Lang): Lang { return l === 'es' ? 'eu' : 'es'; }
export function withLang(lang: Lang, path: string): string {
  const clean = path.startsWith('/') ? path : `/${path}`;
  if (clean === '/') return `/${lang}`;
  if (clean.startsWith('/es') || clean.startsWith('/eu')) return `/${lang}${clean.slice(3)}`;
  return `/${lang}${clean}`;
}
